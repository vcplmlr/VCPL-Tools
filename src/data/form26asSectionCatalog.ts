export function lookupSectionMeta(sectionCode: string): StatutorySectionMeta {
  const clean = sectionCode.trim().toUpperCase();
  if (STATUTORY_SECTION_CATALOG[clean]) return STATUTORY_SECTION_CATALOG[clean];
  const base = clean.replace(/\(.*$/, '');
  if (STATUTORY_SECTION_CATALOG[base]) return STATUTORY_SECTION_CATALOG[base];

  if (/^10\d{2}$/.test(clean)) {
    return {
      code: clean,
      statutoryRef: '392/393/394',
      oldActEq: '-',
      description: 'Income-tax Act, 2025 — Section 392/393/394',
      standardRatePct: null,
    };
  }
  if (clean.startsWith('206C') || clean.startsWith('394') || clean === 'TCS') {
    return {
      code: clean,
      statutoryRef: '394 / 206C',
      oldActEq: '206C',
      description: 'Tax Collected at Source (TCS)',
      standardRatePct: 1,
    };
  }
  return {
    code: clean || 'TDS',
    statutoryRef: '393 / 194',
    oldActEq: '-',
    description: 'Tax Deducted at Source (TDS)',
    standardRatePct: null,
  };
}
